"""Generate the mobile SQL contract from the authoritative Python implementation."""
from pathlib import Path
import argparse
import ast
import importlib.util
import json
import sys

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "projects/znacpy/znactime/storage/sqlite/schema.py"
TARGET = ROOT / "projects/znac-expo/src/db/schema.ts"


def generated_source():
    spec = importlib.util.spec_from_file_location("canonical_schema", SOURCE)
    module = importlib.util.module_from_spec(spec)
    # Loading via exec avoids writing bytecode into the reference project.
    exec(compile(SOURCE.read_text(encoding="utf-8"), str(SOURCE), "exec"), module.__dict__)
    migration_tree = ast.parse(SOURCE.with_name("migrations.py").read_text(encoding="utf-8"))
    migration_tree.body = [node for node in migration_tree.body if not (
        isinstance(node, ast.ImportFrom) and node.module == "znactime.storage.sqlite.schema"
    )]
    migrations = dict(module.__dict__)
    exec(compile(migration_tree, "migrations.py", "exec"), migrations)
    manifest = [[kind, name, sql] for (kind, name), sql in sorted(module.expected_schema_manifest().items())]
    return (
        "// Generated by scripts/sync-python-schema.py. Edit the Python reference, then regenerate.\n"
        f"export const CURRENT_SCHEMA_VERSION = {module.SCHEMA_VERSION};\n\n"
        "export const CREATE_SCHEMA_SQL = " + json.dumps(module.SCHEMA_SQL, ensure_ascii=False) + ";\n\n"
        "export const SCHEMA_MANIFEST: readonly (readonly string[])[] = "
        + json.dumps(manifest, ensure_ascii=False, indent=2) + ";\n"
        + "\nexport const PYTHON_MIGRATIONS: Readonly<Record<number, string>> = "
        + json.dumps(migrations["MIGRATIONS"], ensure_ascii=False, indent=2) + ";\n"
        + "\nexport const INITIAL_V6_MANIFEST: readonly (readonly string[])[] = "
        + json.dumps([[kind, name, sql] for (kind, name), sql in sorted(module.initial_v6_schema_manifest().items())], ensure_ascii=False, indent=2) + ";\n"
        + "\nexport const AMEND_INITIAL_V6_SQL = " + json.dumps(migrations["MIGRATION_V6_AMENDMENT"], ensure_ascii=False) + ";\n"
        + "\nexport const PYTHON_V6_SQL = " + json.dumps(module.SCHEMA_V6_SQL, ensure_ascii=False) + ";\n"
        + "\nexport const PYTHON_INITIAL_V6_SQL = " + json.dumps(module.SCHEMA_V6_INITIAL_SQL, ensure_ascii=False) + ";\n"
        + "\nexport const PYTHON_V6_MANIFEST: readonly (readonly string[])[] = "
        + json.dumps([[kind, name, sql] for (kind, name), sql in sorted(module.v6_schema_manifest().items())], ensure_ascii=False, indent=2) + ";\n"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = generated_source()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != source:
            sys.exit("Mobile SQLite contract differs from Python. Run scripts/sync-python-schema.py.")
        print("SQLite schema and manifest match the Python reference.")
    else:
        TARGET.write_text(source, encoding="utf-8", newline="\n")
        print("Generated mobile SQLite contract from Python.")
